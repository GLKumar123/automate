import json
import os
import sys
import time
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

import requests


BASE_DIR = Path(__file__).resolve().parent.parent
REPORT_DIR = BASE_DIR / "reports"

INCIDENT_FILE = REPORT_DIR / "incidents.json"
SUMMARY_FILE = REPORT_DIR / "incident-summary.json"

IST = ZoneInfo("Asia/Kolkata")

# Leave room below typical webhook/message limits.
MAX_MESSAGE_CHARS = 18000
MAX_RETRIES = 3

PRIORITY_ORDER = [
    "P1 - Critical",
    "P2 - High",
    "P3 - Moderate",
    "P4 - Low",
    "P5 - Planning",
]

STATE_ORDER = [
    "New",
    "In Progress",
    "On Hold",
    "Resolved",
    "Closed",
    "Canceled",
]


def load_json(path):
    with path.open("r", encoding="utf-8") as file:
        return json.load(file)


def report_time():
    return datetime.now(IST).strftime("%Y-%m-%d %I:%M:%S %p IST")


def safe_text(value, default="Not available"):
    if value is None:
        return default

    value = str(value).strip()
    return value if value else default


def format_summary(incidents, summary):
    lines = [
        "SERVICENOW INCIDENT STATUS REPORT",
        f"Report Time: {report_time()}",
        "",
        "SUMMARY",
        f"Total Incidents: {summary['total_incidents']}",
        "",
        "PRIORITY",
    ]

    priority_counts = summary.get("priority_counts", {})

    for priority in PRIORITY_ORDER:
        lines.append(
            f"{priority}: {priority_counts.get(priority, 0)}"
        )

    # Include any unexpected/custom priority values.
    for priority, count in priority_counts.items():
        if priority not in PRIORITY_ORDER:
            lines.append(f"{priority}: {count}")

    lines.extend(["", "STATE"])

    state_counts = summary.get("state_counts", {})

    for state in STATE_ORDER:
        lines.append(f"{state}: {state_counts.get(state, 0)}")

    for state, count in state_counts.items():
        if state not in STATE_ORDER:
            lines.append(f"{state}: {count}")

    lines.extend([
        "",
        "=" * 50,
        "",
        "INDIVIDUAL INCIDENT DETAILS",
        "",
    ])

    for index, incident in enumerate(incidents, start=1):
        notes = incident.get("work_notes", [])
        lines.extend([
            f"{index}. Incident: {safe_text(incident.get('number'))}",
            f"   Priority: {safe_text(incident.get('priority'))}",
            f"   Status: {safe_text(incident.get('state'))}",
            f"   Assigned To: {safe_text(incident.get('assigned_to'), 'Unassigned')}",
            f"   Assignment Group: {safe_text(incident.get('assignment_group'), 'Unassigned')}",
            f"   Description: {safe_text(incident.get('description') or incident.get('short_description'))}",
            "   Work Notes:",
        ])

        if notes:
            for note in notes:
                if not isinstance(note, dict):
                    continue

                note_text = safe_text(note.get("note"), "")
                if not note_text:
                    continue

                created_at = safe_text(note.get("created_at"), "")
                created_by = safe_text(note.get("created_by"), "")

                lines.append(
                    f"     [{created_at} | {created_by}] {note_text}"
                )
        else:
            lines.append("     No work notes available.")

        lines.extend([
            f"   Created: {safe_text(incident.get('sys_created_on'))}",
            f"   Last Updated: {safe_text(incident.get('sys_updated_on'))}",
            "",
            "-" * 50,
            "",
        ])

    lines.extend([
        "=" * 50,
        "",
        "DETAILED REPORTS",
        f"GitHub Actions Run: {os.getenv('GITHUB_SERVER_URL', 'https://github.com')}/"
        f"{os.getenv('GITHUB_REPOSITORY', '')}/actions/runs/"
        f"{os.getenv('GITHUB_RUN_ID', '')}",
        "",
        "Generated by GitHub Actions.",
    ])

    return "\n".join(lines)


def split_message(text, max_chars=MAX_MESSAGE_CHARS):
    """Split a long report into chunks without losing lines."""
    chunks = []
    current_lines = []
    current_length = 0

    for line in text.splitlines():
        line_length = len(line) + 1

        if current_lines and current_length + line_length > max_chars:
            chunks.append("\n".join(current_lines))
            current_lines = []
            current_length = 0

        # Handle an unusually long individual line.
        while len(line) > max_chars:
            if current_lines:
                chunks.append("\n".join(current_lines))
                current_lines = []
                current_length = 0

            chunks.append(line[:max_chars])
            line = line[max_chars:]

        if line:
            current_lines.append(line)
            current_length += len(line) + 1

    if current_lines:
        chunks.append("\n".join(current_lines))

    return chunks


def post_to_teams(webhook_url, message):
    """
    Send a text payload.

    Configure the Teams Workflow to read the incoming JSON property
    'text' and post that value to the target channel.
    """
    payload = {"text": message}

    for attempt in range(MAX_RETRIES):
        try:
            response = requests.post(
                webhook_url,
                json=payload,
                headers={"Content-Type": "application/json"},
                timeout=30,
            )

            if response.status_code in (429, 500, 502, 503, 504):
                if attempt < MAX_RETRIES - 1:
                    retry_after = response.headers.get("Retry-After")
                    try:
                        delay = min(int(retry_after), 30) if retry_after else 2 ** attempt
                    except ValueError:
                        delay = 2 ** attempt

                    time.sleep(delay)
                    continue

            response.raise_for_status()
            return

        except requests.RequestException:
            if attempt == MAX_RETRIES - 1:
                raise

            time.sleep(2 ** attempt)


def main():
    webhook_url = os.getenv("TEAMS_WEBHOOK_URL", "").strip()

    if not webhook_url:
        print("ERROR: TEAMS_WEBHOOK_URL is not configured.", file=sys.stderr)
        sys.exit(1)

    try:
        incidents = load_json(INCIDENT_FILE)
        summary = load_json(SUMMARY_FILE)

        if not isinstance(incidents, list):
            raise ValueError("Incident report must be a JSON list.")

        report = format_summary(incidents, summary)
        chunks = split_message(report)

        total_chunks = len(chunks)

        for index, chunk in enumerate(chunks, start=1):
            if total_chunks > 1:
                chunk = (
                    f"ServiceNow Incident Status Report "
                    f"({index}/{total_chunks})\n\n{chunk}"
                )

            post_to_teams(webhook_url, chunk)
            print(f"Posted Teams message {index}/{total_chunks}")

        print("ServiceNow incident report sent successfully.")

    except (
        OSError,
        ValueError,
        json.JSONDecodeError,
        requests.RequestException,
    ) as exc:
        print(f"ERROR: Teams report delivery failed: {exc}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
